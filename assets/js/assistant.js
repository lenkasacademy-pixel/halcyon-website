    if (st === 'phone') q = (S.d.name ? 'Thanks, ' + S.d.name + '. ' : '') + 'Which mobile number should they call?';
    say((lead || '') + q, null, null, ui(st));
    chips(FLOW[st].chips.map(function (l) { return { label: l }; }));
